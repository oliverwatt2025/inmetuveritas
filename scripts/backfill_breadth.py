#!/usr/bin/env python3
"""One-time SPY/RSP breadth backfill. Leaves FRED readings and other fields intact."""
import json
from datetime import datetime
from update_indicators import market_daily_closes, HISTORY_DAILY, HISTORY_WEEKLY, load_daily_history, load_weekly_history

def returns_by_day(bars, lookback=20):
    ordered = sorted(bars, key=lambda b: b.date)
    return {ordered[i].date: (ordered[i].close / ordered[i-lookback].close - 1) * 100
            for i in range(lookback, len(ordered)) if ordered[i-lookback].close > 0}

def save_ndjson(path, rows):
    path.write_text("".join(json.dumps(row, separators=(",", ":")) + "\n" for row in rows), encoding="utf-8")

def main():
    spy = returns_by_day(market_daily_closes("spy.us"))
    rsp = returns_by_day(market_daily_closes("rsp.us"))
    dates = sorted(set(spy) & set(rsp))
    if len(dates) < 30:
        raise RuntimeError(f"Insufficient aligned daily closes: {len(dates)}")
    # The same 20-trading-session RSP minus SPY return used for today's dial.
    calculated = {day: round(rsp[day] - spy[day], 1) for day in dates}
    rows = {row["date"]: row for row in load_daily_history() if isinstance(row.get("date"), str)}
    for day, breadth in calculated.items():
        record = rows.setdefault(day, {"date": day})
        # Keep values generated by the routine daily updater if already present.
        record.setdefault("breadth", breadth)
    save_ndjson(HISTORY_DAILY, [rows[day] for day in sorted(rows)])

    # Weekly history is one Monday-keyed snapshot. Fill ONLY missing breadth keys.
    weekly = {row["week"]: row for row in load_weekly_history() if isinstance(row.get("week"), str)}
    for day in dates:
        date = datetime.strptime(day, "%Y-%m-%d").date()
        monday = date.fromordinal(date.toordinal() - date.weekday()).isoformat()
        weekly.setdefault(monday, {"week": monday}).setdefault("breadth", calculated[day])
    save_ndjson(HISTORY_WEEKLY, [weekly[week] for week in sorted(weekly)])
    print(f"Backfilled breadth through {dates[-1]} using {len(dates)} aligned trading dates; existing FRED data retained.")

if __name__ == "__main__":
    main()
